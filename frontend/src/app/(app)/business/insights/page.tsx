"use client";

import React, { useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import axios from 'axios';
import { Database, Lightbulb, Target, ArrowRight, Info, ChevronRight } from 'lucide-react';
import { motion } from 'framer-motion';
import { 
  PageContainer, 
  SectionHeader, 
  Card, 
  LoadingSkeleton, 
  StatusBadge 
} from '@/components/ui/design-system';

export default function InsightsPage() {
  const [selectedDataset, setSelectedDataset] = useState<string | null>(null);

  const { data: history } = useQuery({
    queryKey: ['datasetHistory'],
    queryFn: async () => {
      const res = await axios.get(`${process.env.NEXT_PUBLIC_API_URL}/api/v1/dataset/history`);
      const hist = res.data.history;
      if (hist && hist.length > 0 && !selectedDataset) {
        setSelectedDataset(hist[hist.length - 1].name);
      }
      return hist;
    }
  });

  const { data: insightsData, isLoading: isLoadingInsights } = useQuery({
    queryKey: ['insights', selectedDataset],
    queryFn: async () => {
      if (!selectedDataset) return null;
      const res = await axios.get(`${process.env.NEXT_PUBLIC_API_URL}/api/v1/platform/insights?dataset_name=${selectedDataset}`);
      return res.data.data;
    },
    enabled: !!selectedDataset
  });

  const { data: recommendationsData, isLoading: isLoadingRecs } = useQuery({
    queryKey: ['recommendations', selectedDataset],
    queryFn: async () => {
      if (!selectedDataset) return null;
      const res = await axios.get(`${process.env.NEXT_PUBLIC_API_URL}/api/v1/platform/recommendations?dataset_name=${selectedDataset}`);
      return res.data.data;
    },
    enabled: !!selectedDataset
  });

  return (
    <PageContainer>
      <SectionHeader 
        title="Business Intelligence" 
        description="Strategic insights and recommendations generated by the LLM Agent."
      />

      <Card hover={false} className="p-4 flex items-center justify-between">
        <div className="flex items-center w-full md:w-auto">
          <Database className="w-4 h-4 mr-3 text-[#5B5CEB]" />
          <div className="relative flex-1 sm:flex-initial">
            <select 
              value={selectedDataset || ""} 
              onChange={(e) => setSelectedDataset(e.target.value)}
              className="bg-transparent text-sm font-bold text-[#111827] focus:outline-none w-64 pr-8 cursor-pointer appearance-none"
            >
              <option value="" disabled>Select active dataset</option>
              {history?.map((d: any, i: number) => (
                <option key={i} value={d.name}>{d.name}</option>
              ))}
            </select>
            <ChevronRight className="w-3.5 h-3.5 text-[#9CA3AF] pointer-events-none absolute right-0 top-1/2 -translate-y-1/2 rotate-90" />
          </div>
        </div>
      </Card>

      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        
        {/* Insights Section */}
        <Card hover={false} className="flex flex-col min-h-[480px]">
          <div className="flex justify-between items-center mb-6 pb-3 border-b border-[#E7EAF2]">
            <h3 className="text-sm font-bold text-[#111827] flex items-center">
              <Lightbulb className="w-4 h-4 text-[#F59E0B] mr-2 animate-pulse" /> Key Insights
            </h3>
            <StatusBadge status="LLM Heuristics" type="warning" />
          </div>
          
          <div className="flex-1 space-y-4">
            {isLoadingInsights ? (
              <div className="space-y-4">
                <LoadingSkeleton className="h-20 w-full" />
                <LoadingSkeleton className="h-20 w-full" />
                <LoadingSkeleton className="h-20 w-full" />
              </div>
            ) : insightsData && insightsData.insights ? (
              insightsData.insights.map((insight: string, i: number) => (
                <motion.div 
                  initial={{ opacity: 0, y: 10 }} 
                  animate={{ opacity: 1, y: 0 }} 
                  transition={{ delay: i * 0.08 }}
                  key={i} 
                  className="p-4 rounded-xl bg-[#F8F9FC] border border-[#E7EAF2] text-xs font-semibold text-[#4B5563] leading-relaxed whitespace-pre-wrap select-text font-serif"
                >
                  {insight}
                </motion.div>
              ))
            ) : (
              <div className="flex flex-col items-center justify-center text-[#9CA3AF] h-64 border border-[#E7EAF2] border-dashed rounded-2xl bg-[#F8F9FC]/40">
                <Info className="w-6 h-6 mb-2 opacity-50 text-[#9CA3AF]" />
                <span className="text-xs font-bold uppercase tracking-wider">No insights generated.</span>
              </div>
            )}
          </div>
        </Card>

        {/* Recommendations Section */}
        <Card hover={false} className="flex flex-col min-h-[480px]">
          <div className="flex justify-between items-center mb-6 pb-3 border-b border-[#E7EAF2]">
            <h3 className="text-sm font-bold text-[#111827] flex items-center">
              <Target className="w-4 h-4 text-[#5B5CEB] mr-2" /> Prescriptive Actions
            </h3>
            <StatusBadge status="Strategic Advice" type="success" />
          </div>
          
          <div className="flex-1 space-y-4">
            {isLoadingRecs ? (
              <div className="space-y-4">
                <LoadingSkeleton className="h-20 w-full" />
                <LoadingSkeleton className="h-20 w-full" />
                <LoadingSkeleton className="h-20 w-full" />
              </div>
            ) : recommendationsData && recommendationsData.actions ? (
              recommendationsData.actions.map((action: string, i: number) => (
                <motion.div 
                  initial={{ opacity: 0, x: 10 }} 
                  animate={{ opacity: 1, x: 0 }} 
                  transition={{ delay: i * 0.08 }}
                  key={i} 
                  className="flex items-start p-4 rounded-xl bg-white border border-[#E7EAF2] hover:border-[#5B5CEB]/40 hover:shadow-sm transition-all group cursor-default shadow-[0_4px_20px_rgba(0,0,0,0.002)]"
                >
                  <ArrowRight className="w-3.5 h-3.5 text-[#5B5CEB] group-hover:translate-x-0.5 transition-transform mr-3 mt-0.5 shrink-0" />
                  <div className="text-xs font-semibold text-[#111827] leading-relaxed whitespace-pre-wrap select-text font-serif">
                    {action}
                  </div>
                </motion.div>
              ))
            ) : (
              <div className="flex flex-col items-center justify-center text-[#9CA3AF] h-64 border border-[#E7EAF2] border-dashed rounded-2xl bg-[#F8F9FC]/40">
                <Info className="w-6 h-6 mb-2 opacity-50 text-[#9CA3AF]" />
                <span className="text-xs font-bold uppercase tracking-wider">No actions prescribed.</span>
              </div>
            )}
          </div>
        </Card>

      </div>
    </PageContainer>
  );
}
